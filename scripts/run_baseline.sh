#!/usr/bin/env bash
# Phase 2 reproducible baseline run (exit-gate evidence).
# The scenario clock is pinned to 2026-10-12 so eligibility math is deterministic
# against the frozen fixtures, regardless of the wall date.
set -euo pipefail
cd "$(dirname "$0")/.."

PY="${PYTHON:-python3}"
if [[ -z "${VIRTUAL_ENV:-}" ]]; then
  echo "warning: no virtualenv active; expected ../.venv or your project venv" >&2
fi

export PYTHONPATH=src
mkdir -p artifacts
rm -f artifacts/baseline_run.log

{
  echo "# baseline demo outputs — generated by scripts/run_baseline.sh, clock pinned 2026-10-12"
  "$PY" -m capstone_agent.baseline_agent --demo --today 2026-10-12 --log artifacts/baseline_run.log
} | tee artifacts/baseline_demo_outputs.txt

echo
echo "evidence written:"
echo "  artifacts/baseline_run.log          ($(wc -l < artifacts/baseline_run.log | tr -d ' ') sanitized JSONL request lines)"
echo "  artifacts/baseline_demo_outputs.txt"
